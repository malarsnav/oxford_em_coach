const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const app = fs.readFileSync(path.join(__dirname,'../src/app.js'),'utf8');
const source = app.slice(app.indexOf('function weeklyProgressChartHtml('), app.indexOf('function weeklyReportHtml('));
const context = vm.createContext({escapeAttr:s=>String(s).replaceAll('"','&quot;')});
vm.runInContext(source,context);
const day = {date:'2026-10-12',trackingStarted:true,total:8,logged:4,skipped:1,overdue:2,upcoming:2};
context.report = {days:[day,{...day,date:'2026-10-13',total:4,logged:4,skipped:0,overdue:0,upcoming:0}]};
let html = vm.runInContext('weeklyProgressChartHtml(report)',context);
assert.ok(html.includes('width:50%'));
assert.ok(html.includes('width:100%'));
assert.ok(html.includes('4 logged of 8 planned blocks; 1 skipped; 2 elapsed not logged'));
assert.ok(html.includes('4/4 logged'));
context.report={days:[{...day,trackingStarted:false,total:0,logged:0}]};
html=vm.runInContext('weeklyProgressChartHtml(report)',context);
assert.ok(html.includes('Not tracked'));
assert.ok(!html.includes('NaN') && !html.includes('Infinity'));
console.log('Weekly chart: shared scale, counts, skipped distinction and empty state passed.');
