const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const context=vm.createContext({Date,Set,Map});
for(const file of ['studentStudyPlan.js','mathsSyllabus.js','furtherMathsTopics.js','studySyllabuses.js','planTracking.js','dailyStudyReport.js'])vm.runInContext(fs.readFileSync(path.join(root,'src',file),'utf8').replace(/^import .*;$/gm,'').replaceAll('export ',''),context);
const run=s=>vm.runInContext(s,context);
assert.equal(run('MATHS_TOPICS.length'),19);
assert.equal(run('MATHS_TOPICS.filter(g=>g.section==="Pure").flatMap(g=>g.items).length'),62);
assert.equal(run('MATHS_TOPICS.filter(g=>g.section!=="Pure").flatMap(g=>g.items).length'),27);
assert.equal(run('new Set(MATHS_ITEMS.map(i=>i.id)).size'),run('MATHS_ITEMS.length'));
assert.equal(run('areaFor("Maths tuition")'),'Maths');
assert.equal(run('areaFor("SMC")'),'Super Curricular');
assert.equal(run('scheduledAreas().has("Super Curricular")'),true);
assert.equal(run('scheduledAreas().has("Magazine")'),false);
assert.equal(run('scheduledAreas().has("TARA")'),false);
assert.equal(run('scheduledAreas("Saturday").has("Book")'),false);
assert.equal(run('richStudyFields("AS Maths").includes("topic-picker")'),true);
assert.equal(run('richStudyFields("Maths").includes("topic-picker")'),true);
assert.ok(run('availabilityHtml("date","2026-09-05","Maths")').includes('Not scheduled today'));
assert.equal(run('AS_MATHS.topics.length'),17);
assert.equal(run('AS_MATHS.topics.filter(g=>g.section==="Pure").flatMap(g=>g.items).length'),34);
assert.equal(run('AS_PHYSICS.topics.length'),14);
assert.equal(run('AS_PHYSICS.topics.flatMap(g=>g.items).length'),39);
assert.equal(run('syllabusFor("Economics").topics.length'),10);
assert.equal(run('syllabusFor("Economics","full").topics.length'),21);
assert.equal(run('syllabusFor("History").topics.length'),5);
assert.equal(run('syllabusFor("History","full").topics.length'),10);
assert.equal(run('new Set(SYLLABUS_ITEMS.map(i=>i.id)).size'),run('SYLLABUS_ITEMS.length'));
assert.equal(run('richStudyFields("Maths").includes("edexcel-9ma0-issue4:Pure:2.3")'),false);
assert.equal(run('richStudyFields("Maths",{details:{spec:"edexcel-9ma0-issue4"}}).includes("edexcel-9ma0-issue4:Pure:2.3")'),true);
assert.equal(run('richStudyFields("History").includes("Yezhovshchina")'),false);
assert.equal(run('richStudyFields("History").includes("Great Turn")'),true);
assert.equal(run('areaFor("AS Maths")'),'AS-Further Maths');
assert.equal(run('syllabusFor("AS-Further Maths").id'),'edexcel-8fm0-issue5');
assert.equal(run('AS_FURTHER_MATHS.topics.length'),37);
assert.equal(run('AS_FURTHER_MATHS.topics.filter(g=>g.section==="Core Pure").flatMap(g=>g.items).length'),25);
assert.equal(run('dailyStudyReport([],new Date(2026,8,5,8)).total'),8);
assert.equal(run('dailyStudyReport([],new Date(2026,8,7,8)).total'),5);
assert.equal(run('dailyStudyReport([],new Date(2026,8,5,8)).upcoming'),8);
assert.equal(run('dailyStudyReport([],new Date(2026,8,5,10)).overdue'),1);
assert.equal(run('dailyStudyReport([{log_date:"2026-09-04",start_time:"09:00",end_time:"10:00",planned_activity:"Maths"}],new Date(2026,8,5,10)).logged'),0);
const sample='[{log_date:"2026-09-05",start_time:"09:00:00",end_time:"10:00:00",planned_activity:"Maths"},{log_date:"2026-09-05",start_time:"15:30",end_time:"15:45",planned_activity:"Magazine"}]';
assert.equal(run(`dailyStudyReport(${sample},new Date(2026,8,5,10)).logged`),1);
assert.equal(run(`dailyStudyReport(${sample},new Date(2026,8,5,10)).extra.length`),1);
assert.equal(run(`dailyStudyReport(${sample},new Date(2026,8,5,10)).loggedMinutes`),60);
assert.equal(run(`dailyStudyReport(${sample},new Date(2026,8,5,10)).percent`),13);
assert.equal(run('dailyStudyReport([],new Date(2026,8,5,12),"2026-09-04").overdue'),5);
assert.equal(run('dailyStudyReport([],new Date(2026,8,5,12),"2026-09-06").upcoming'),8);
assert.equal(run('logArea({planned_activity:"Maths",details:{outcome:"changed",actual_activity:"Physics"}})'),'Physics');
assert.equal(run('logArea({planned_activity:"Maths",details:{outcome:"skipped"}})'),null);
assert.equal(run('weeklyStudyReport([],new Date(2026,8,5,12)).start'),'2026-08-31');
assert.equal(run('weeklyStudyReport([],new Date(2026,8,5,12)).end'),'2026-09-06');
assert.equal(run('weeklyStudyReport([],new Date(2026,8,5,12)).total'),41);
assert.equal(run('weeklyStudyReport([],new Date(2026,8,5,12),"2026-08-24").missed'),41);
assert.equal(run('weeklyStudyReport([],new Date(2026,8,5,12),"2026-09-07").missed'),0);
assert.equal(run(`weeklyStudyReport(${sample},new Date(2026,8,5,12)).logged`),1);
assert.equal(run(`weeklyStudyReport(${sample},new Date(2026,8,5,12)).extra`),1);
const changed='[{log_date:"2026-09-05",start_time:"09:00",end_time:"10:00",planned_activity:"Maths",details:{outcome:"changed",actual_activity:"Physics"}}]';
assert.equal(run(`weeklyStudyReport(${changed},new Date(2026,8,5,12)).subjects.find(s=>s.name==="Physics").actual`),1);
assert.equal(run(`weeklyStudyReport(${changed},new Date(2026,8,5,12)).subjects.find(s=>s.name==="Maths").actual`),0);
assert.equal(run(`weeklyStudyReport(${changed.replace('changed','skipped')},new Date(2026,8,5,12)).skipped`),1);
assert.equal(run(`weeklyStudyReport(${changed.replace('changed','skipped')},new Date(2026,8,5,12)).subjects.find(s=>s.name==="Physics").actual`),0);
console.log('Syllabus, compatibility, daily and weekly report checks passed.');
